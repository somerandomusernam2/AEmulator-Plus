def walk(read, start, end, limit=100000):
    a=start; out=[]
    while a<end and len(out)<limit:
        op=read(a,1)[0]
        n=SZ.get(op)
        if n is None: out.append((a,op,None,b'')); break
        out.append((a,op,NAME.get(op,'?'),read(a,n)))
        if op==0: break
        a+=n
    return out
def fmt(e):
    a,op,nm,b=e
    return '%08x: %-28s %s'%(a,nm or 'UNKNOWN(%d)'%op,b[1:].hex())
